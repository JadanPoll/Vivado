#!/usr/bin/env python3
"""Behavioral state-space exploration for JadanPoll/Vivado.

Read together with the source anchors in SOURCES.  Models public component
contracts and async interleavings, not Verilog gates, routing algorithms,
JTAG timing or browser execution. Old revisions, disconnects, interrupted
builds, partial commands, and warnings are ALLOWED.

Rather than cross-product every unrelated event, explore dependency-closed
projections of a common transition system (bounded partial-order reduction).
Every trace is generated by breadth-first search; assertions test outcomes,
not the mere occurrence of permitted events.

Run: python3 tests/system_behavior_model.py --json
"""
from __future__ import annotations
from dataclasses import dataclass, replace
from collections import deque
from itertools import permutations
import argparse
import json

SOURCES = {
  "editor": "FINAL/index.html:1084-1115,1227-1265",
  "github": "FINAL/index.html:705-720,767-886",
  "fasm": "FINAL/index.html:1183-1238; PRODUCTION_GRADE/fasm2frames2.js",
  "jtag": "PRODUCTION_GRADE/ftdi-jtag.js:programXC7",
  "ble": "PRODUCTION_GRADE/urbana-ble.js:write/_processIncoming",
  "stopwatch": "PRODUCTION_GRADE/DEFAULTS/stopwatch/top.v",
  "pins": "PRODUCTION_GRADE/DEFAULTS/stopwatch/top.xdc",
}

# The same state type is used by every projection. -1 = no artifact/request.
@dataclass(frozen=True)
class State:
    remote: int = 0
    discover_request: int = -1
    discovered: int = -1
    load_request: int = -1
    workspace: int = -1
    visible_source: int = -1
    observed_source: int = -1
    saved_draft: int = -1
    build: str = "idle"
    build_input: int = -1
    artifact: int = -1
    artifact_has_warning: bool = False
    flash: str = "idle"
    clicked_artifact: int = -1
    used_artifact: int = -1
    done_pin: int = -1
    ui_flash_success: bool = False
    flash_error: bool = False
    ble: bool = False
    rx: str = ""
    running: bool = False
    tx: str = "idle"
    reply_received: bool = False
    known_mapping: tuple[int,...] = ()
    pin_map: tuple[int,...] = (0,1,2,3)
    logic_order: tuple[int,...] = (0,1,2,3)

def transitions(s: State, repaired: bool = False):
    """(domain, English event, next state). Nondeterministic outcomes branch."""
    def step(domain, event, **kw):
        return (domain, event, replace(s, **kw))
    # GitHub pinning means a remote commit doesn't mutate the loaded snapshot.
    if s.remote == 0:
        yield step("github", "remote repo advances to revision 1", remote=1)
    if s.discover_request == -1:
        yield step("github", "start GitHub discovery", discover_request=s.remote)
    else:
        yield step("github", "pinned discovery resolves", discovered=s.discover_request,
                   discover_request=-1)
        yield step("github", "discovery network error", discover_request=-1)
    if s.discovered!=-1 and s.load_request==-1:
        yield step("github", "start workspace file fetch", load_request=s.discovered)
    if s.load_request!=-1:
        yield step("github", "workspace fetch completes", workspace=s.load_request,
                   visible_source=s.load_request, observed_source=s.load_request,
                   load_request=-1)
        yield step("github", "workspace fetch interrupted", load_request=-1)
    if s.visible_source!=-1 and s.visible_source<2:
        yield step("editor", "edit current HDL without compiling", visible_source=s.visible_source+1)
    if s.visible_source!=-1:
        if s.saved_draft != s.visible_source:
            yield step("editor", "save current local draft", saved_draft=s.visible_source)
        if s.build in ("idle","ready","failed"):
            # Build button remains usable even if a flash is already awaiting USB.
            yield step("build", "start build using visible input snapshot",
                       build="yosys", build_input=s.visible_source,
                       artifact=-1, artifact_has_warning=False)
    if s.build=="yosys":
        yield step("build", "Yosys succeeds", build="pnr")
        yield step("build", "Yosys fails", build="failed")
    if s.build=="pnr":
        yield step("build", "nextpnr succeeds", build="fasm")
        yield step("build", "nextpnr fails", build="failed")
    if s.build=="fasm":
        yield step("build", "all FASM features recognized", build="frames")
        yield step("build", "FASM emits frames with an unmapped-feature warning",
                   build="frames", artifact_has_warning=True)
        yield step("build", "FASM conversion fails", build="failed")
    if s.build=="frames":
        yield step("build", "bitstream assembly succeeds", build="ready",
                   artifact=s.build_input)
        yield step("build", "bitstream assembly fails", build="failed")
    if s.artifact!=-1 and s.flash in ("idle","complete","failed"):
        yield step("flash", "click Flash on ready artifact", flash="permission",
                   clicked_artifact=s.artifact, used_artifact=-1,
                   done_pin=-1, ui_flash_success=False, flash_error=False)
    if s.flash=="permission":
        yield step("flash", "USB permission granted", flash="jtag_init")
        yield step("flash", "USB permission denied", flash="failed",flash_error=True)
    if s.flash=="jtag_init":
        yield step("flash", "FTDI/JTAG interface initialized",flash="idcode")
        yield step("flash", "interface init raises error",flash="failed",flash_error=True)
    if s.flash=="idcode":
        yield step("flash", "silicon IDCODE matches",flash="program")
        yield step("flash", "silicon IDCODE mismatch",flash="failed",flash_error=True)
    if s.flash=="program":
        # IMPORTANT: index.html reads the mutable pipelineState.bitstream HERE,
        # following all permission / init / IDCODE awaits, not at click time.
        # Baseline uses mutable global pipelineState; the repaired handler
        # captures the selected buffer before the first await.
        selected=s.clicked_artifact if repaired else s.artifact
        if selected==-1:
            yield step("flash", "programXC7 reads null pipelineState.bitstream",
                       flash="failed",flash_error=True)
        else:
            for bit in (0,1):
                # DONE=0 is a legal device outcome. It is a contract breach
                # only if the UI subsequently reports successful programming.
                if repaired and bit==0:
                    yield step("flash", "DONE=0 causes rejection and visible flash error",
                               flash="failed",used_artifact=selected,
                               done_pin=bit,flash_error=True)
                else:
                    yield step("flash", f"JTAG readStatus reports DONE={bit}; method resolves",
                               flash="complete",used_artifact=selected,
                               done_pin=bit,ui_flash_success=True)
            yield step("flash", "USB transfer or status read throws",
                       flash="failed",flash_error=True)
    if not s.ble:
        yield step("ble", "BLE reconnect",ble=True)
    else:
        yield step("ble", "BLE disconnect",ble=False)
        if s.rx=="":
            yield step("ble", "receive letter s without LF",rx="s")
        if s.rx=="s":
            yield step("ble", "LF arrives and command is decoded",rx="",running=True,tx="queued")
    if s.tx=="queued":
        yield step("ble", "begin transmitting reply",tx="sending")
    if s.tx=="sending":
        yield step("ble", "finish UART reply",tx="idle",reply_received=s.ble)
    # Observation is derived from the composition; no 'wrong map' event by fiat.
    if not s.known_mapping:
        observed=tuple(s.logic_order[s.pin_map[i]] for i in range(4))
        yield step("display", "observe four physical digit positions",
                   known_mapping=observed)
    if s.pin_map==(0,1,2,3):
        yield step("display", "swap physical anode 0 and 1",pin_map=(1,0,2,3))
    if s.logic_order==(0,1,2,3):
        yield step("display", "reverse logical digit selection",logic_order=(3,2,1,0))

# These are genuinely normative source/API contracts, not freshness wishes.
def contract_failures(s: State):
    if s.ui_flash_success and s.done_pin!=1:
        yield "FALSE_FLASH_SUCCESS"
    if s.ui_flash_success and s.used_artifact!=s.clicked_artifact:
        yield "FLASH_SELECTED_ARTIFACT_CHANGED"
    # Every successfully loaded tree is pinned to one GitHub commit.
    # The model does not attempt to infer desired recency or display orientation.

def observations(s: State):
    """Interesting but ACCEPTABLE results, not asserted errors."""
    if s.artifact!=-1 and s.artifact!=s.visible_source:
        yield "older_bitstream_after_edit_allowed"
    if s.artifact_has_warning and s.build=="ready":
        yield "ready_with_explicit_FASM_warning_allowed"
    if s.observed_source!=-1 and s.observed_source!=s.remote:
        yield "observation_outdated_allowed"
    if s.tx=="sending" and not s.ble:
        yield "serial_reply_during_disconnect_allowed"
    if s.known_mapping and s.known_mapping!=tuple(s.logic_order[s.pin_map[i]] for i in range(4)):
        yield "physical_observation_changed_after_edit_allowed"

def bfs(domains,depth=15,max_states=250000,seed=None,repaired=False):
    seed=seed if seed is not None else State()
    q=deque([seed]);visited={seed:(0,None,None)}
    bad={};permitted={};edges=0
    truncated=False
    def trace(u):
        steps=[]
        while visited[u][1] is not None:
            _,pr,label=visited[u];steps.append(label);u=pr
        return steps[::-1]
    while q:
        s=q.popleft();d=visited[s][0]
        for name in contract_failures(s):
            if name not in bad:
                bad[name]={"depth":d,"events":trace(s),
                           "clicked_artifact":s.clicked_artifact,
                           "used_artifact":s.used_artifact,"done_pin":s.done_pin}
        for name in observations(s):
            if name not in permitted:
                permitted[name]={"depth":d,"events":trace(s)}
        if d>=depth:continue
        for domain,label,n in transitions(s,repaired=repaired):
            if domain not in domains:continue
            edges+=1
            if n in visited:continue
            if len(visited)>=max_states:
                truncated=True;break
            visited[n]=(d+1,s,label);q.append(n)
        if truncated:break
    return {"domains":sorted(domains),"states":len(visited),"edges":edges,
            "depth":depth,"truncated":truncated,"repaired":repaired,
            "contract_failures":bad,"allowed_observations":permitted}

def exhaustive_digit_orientations():
    """Enumerate all 4! XDC and 4! logic permutations; do not guess visually."""
    perms=list(permutations(range(4)))
    counts={}
    solutions=[]
    for physical in perms:
        for logical in perms:
            seen=tuple(logical[physical[i]] for i in range(4))
            counts[seen]=counts.get(seen,0)+1
            if seen==(0,1,2,3):
                solutions.append((physical,logical))
    # There is no unique inverse from visible order alone: pin assignment
    # must be constrained independently from manufacturer documentation.
    canonical=[logical for physical,logical in solutions if physical==(0,1,2,3)]
    return {"pairings_checked":len(perms)**2,"distinct_observable_orders":len(counts),
            "solutions_for_normal_order":len(solutions),
            "solutions_with_canonical_physical_pins":canonical,
            "constraint":"Physical pins fixed by verified Urbana XDC; vary HDL order"}

def run(depth):
    # Dependency closures, not arbitrary isolated toy scenarios. Every slice
    # draws transitions from the SAME global definition above.
    slices=[
       ("source_build_flash",{"github","editor","build","flash"},depth),
       ("source_build",{"github","editor","build"},depth),
       ("ble_display",{"ble","display"},depth),
       ("interface_interleavings",{"github","editor","build","flash","ble"},min(depth,10)),
    ]
    result={name:bfs(dom,dep) for name,dom,dep in slices}
    # Reachable checkpoint: a user has loaded and built source revision 0.
    # Starting from this state removes unrelated setup interleavings and
    # allows deep exploration of Flash/Build competition.
    ready=State(discovered=0,workspace=0,visible_source=0,
                observed_source=0,build="ready",build_input=0,artifact=0)
    competition=bfs({"editor","build","flash"},depth=15,seed=ready)
    repaired_competition=bfs({"editor","build","flash"},depth=15,seed=ready,repaired=True)
    repaired_flow=bfs({"github","editor","build","flash"},depth=depth,repaired=True)
    return {"source_anchors":SOURCES,"projections":result,
            "flash_concurrency_baseline":competition,
            "flash_concurrency_repaired":repaired_competition,
            "flash_flow_repaired":repaired_flow,
            "digit_permutations":exhaustive_digit_orientations(),
            "caveat":"Bounded compositional abstraction; counterexamples require source/hardware confirmation"}
if __name__=="__main__":
    ap=argparse.ArgumentParser()
    ap.add_argument("--depth",type=int,default=15)
    ap.add_argument("--json",action="store_true")
    a=ap.parse_args();r=run(a.depth)
    if a.json:print(json.dumps(r,indent=2))
    else:
        for k,v in r["projections"].items():
            print(f"{k}: {v['states']} states, {v['edges']} transitions, depth {v['depth']}, truncated={v['truncated']}")
            for label,ce in v["contract_failures"].items():
                print(f"  CONTRACT FAILURE: {label}: "+ " -> ".join(ce["events"]))
            for label,ce in v["allowed_observations"].items():
                print(f"  Allowed: {label}: "+ " -> ".join(ce["events"]))
        for name in ("flash_concurrency_baseline","flash_concurrency_repaired","flash_flow_repaired"):
            v=r[name]
            print(f"{name}: {v['states']} states, {v['edges']} transitions, depth {v['depth']}, truncated={v['truncated']}")
            for label,ce in v["contract_failures"].items():
                print(f"  CONTRACT FAILURE: {label}: "+" -> ".join(ce["events"]))
        print("Digit orientation search:",r["digit_permutations"])
    assert r["digit_permutations"]["pairings_checked"]==576
    assert any("FALSE_FLASH_SUCCESS" in v["contract_failures"] for v in r["projections"].values())
    assert "FALSE_FLASH_SUCCESS" in r["flash_concurrency_baseline"]["contract_failures"]
    assert "FLASH_SELECTED_ARTIFACT_CHANGED" in r["flash_concurrency_baseline"]["contract_failures"]
    assert not r["flash_concurrency_repaired"]["contract_failures"]
    assert not r["flash_flow_repaired"]["contract_failures"]
